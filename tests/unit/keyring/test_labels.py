@pytest.mark.parametrize(("label", "url", "username"), ACCEPTED, ids=repr)
def test_accepted_label(label: str, url: str, username: str) -> None:
    parsed = parse_label(label)
    assert (parsed.url, parsed.username) == (url, username)


@pytest.mark.parametrize(("label", "problem"), REFUSED, ids=repr)
def test_refused_label(label: str, problem: LabelProblem) -> None:
    with pytest.raises(UnparseableLabelError) as caught:
        parse_label(label)
    assert caught.value.problem is problem
    assert str(caught.value) == problem.value
