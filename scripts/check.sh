# One entry point for every quality gate of spec §12, shared by developers, pre-commit and CI,
# so a gate means the same thing everywhere. Each gate runs to completion even after another
# failed, and a PASS/FAIL/SKIP table at the end lists them all.
set -uo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT" || exit 2

VENV_BIN=${CHECK_VENV_BIN:-$ROOT/.venv/bin}
PYTHON=${CHECK_PYTHON:-$VENV_BIN/python}
PYTEST_WORKERS=${PYTEST_WORKERS:-2}
LOG_DIR=${CHECK_LOG_DIR:-$ROOT/.check-logs}
# reuse lints __pycache__ inside directories git has not seen yet (new test packages before
# their first commit), so the test gates must not leave .pyc files behind.
export PYTHONDONTWRITEBYTECODE=1
# Files generated by `rig apply` from the agent-tools repository. They are linted there and
# editing them here would only be reverted as drift, so their findings are tracked upstream
# (docs/development.md) instead of failing this repository's gates.
RIG_MANAGED_RE='^(ci/|\.serena/|\.haft/|\.github/workflows/(codeql|dependency-review|leftover-grep|pr-checklist|review-threads|secret-scan)\.yml$)'
# Spec §12: coverage >= 90% for the packages that decide what gets written or deleted.
COVERAGE_INCLUDE='src/passwords_app/core/*,src/passwords_app/sync/*,src/passwords_app/store/*,src/passwords_app/keyring/*'
COVERAGE_MIN=90
PYTEST_COMMON=(-p no:cacheprovider -q)
PYTEST_FAST_EXCLUDE='not integration and not e2e and not gui and not browser and not live and not benchmark'

# Group order is the run order of `all`: cheap static gates first, slow suites last.
GATE_GROUPS=(lint types security data extension unit integration coverage gui e2e browser bench)
declare -A GROUP_GATES=(
  [lint]="ruff ruff-format codespell vulture deptry xenon reuse yamllint actionlint zizmor shellcheck shfmt"
  [types]="mypy pyright"
  [security]="bandit semgrep pip-audit gitleaks"
  [data]="dbus-xml desktop-file appstream gschema"
  [extension]="eslint tsc prettier web-ext bun-audit semgrep-ts"
  [unit]=unit
  [integration]=integration
  [coverage]=coverage
  [gui]=gui
  [e2e]=e2e
  [browser]=browser
  [bench]=bench
)

usage() {
  cat <<EOF
usage: scripts/check.sh [--list] [GROUP|GATE ...]

Groups: ${GATE_GROUPS[*]} all (default: all)
Every gate is also selectable by name; --list prints them.
Env: PYTEST_WORKERS (default 2), CHECK_LOG_DIR (default .check-logs), CHECK_PYTHON.
EOF
}

# ---------------------------------------------------------------- bookkeeping
declare -a R_NAME=() R_STATUS=() R_SECS=() R_DETAIL=()
declare -A RAN=()

in_ci() { [[ ${GITHUB_ACTIONS:-} == true ]]; }

record() { # name status seconds detail
  R_NAME+=("$1")
  R_STATUS+=("$2")
  R_SECS+=("$3")
  R_DETAIL+=("$4")
  RAN[$1]=$2
}

# Prefer the project venv so the pinned versions from pyproject win over anything on PATH.
tool() {
  if [[ -x $VENV_BIN/$1 ]]; then
    printf '%s\n' "$VENV_BIN/$1"
  else
    command -v "$1" || true
  fi
}

missing_tool() { # tool... -> prints the first one not installed
  local t
  for t in "$@"; do
    if [[ -z $(tool "$t") ]]; then
      printf '%s\n' "$t"
      return 0
    fi
  done
  return 1
}

# Prefer the tool's own count line ("Found 3 errors", "12 passed"); fall back to the last line
# of output. Bandit prints no single count line, so its issues are counted.
SUMMARY_RE='Found [0-9]+|[0-9]+ (errors?|files? would|passed|failed|findings?|Code Findings)|rank of|no leaks|leaks found|No known vulnerabilities|Files with license information|unused|==>'
summary_of() {
  local line
  if grep -q '^>> Issue:' "$1"; then
    printf '%s bandit issues\n' "$(grep -c '^>> Issue:' "$1")"
    return
  fi
  line=$(grep -E "$SUMMARY_RE" "$1" | tail -n 1)
  [[ -n $line ]] || line=$(grep -v -E '^\s*$|^::(end)?group::' "$1" | tail -n 1)
  printf '%s\n' "$line" | sed -E 's/^[[:space:]│]+//; s/[[:space:]│]+$//' | cut -c1-90
}

skip() { # name reason
  printf '\n== %s: SKIP (%s)\n' "$1" "$2"
  record "$1" SKIP 0 "$2"
}

# run_gate NAME TOOLS -- CMD...   (TOOLS: comma separated binaries that must exist)
run_gate() {
  local name=$1 tools=$2
  shift 3
  local missing log start rc status detail
  local -a needed
  IFS=, read -r -a needed <<<"$tools"
  if missing=$(missing_tool "${needed[@]}"); then
    printf '\n== %s: FAIL (missing tool: %s; see docs/development.md)\n' "$name" "$missing"
    record "$name" FAIL 0 "missing tool: $missing"
    return
  fi
  log=$LOG_DIR/$name.log
  in_ci && printf '::group::%s\n' "$name"
  printf '\n== %s: %s\n' "$name" "$*"
  start=$SECONDS
  "$@" 2>&1 | tee "$log"
  rc=${PIPESTATUS[0]}
  in_ci && printf '::endgroup::\n'
  detail=$(summary_of "$log")
  if ((rc == 0)); then
    status=PASS
  elif ((rc == 5)) && [[ $name =~ ^(unit|integration|gui|e2e|browser|bench)$ ]]; then
    # pytest exit 5 = nothing collected: the suite for this layer does not exist yet.
    status=SKIP
    detail="no tests collected"
  else
    status=FAIL
  fi
  record "$name" "$status" $((SECONDS - start)) "$detail"
}

# ---------------------------------------------------------------- file sets
list_files() { # git-tracked + untracked-not-ignored files matching the pathspecs
  git ls-files -z --cached --others --exclude-standard -- "$@" | tr '\0' '\n' | while IFS= read -r f; do
    [[ -f $f ]] && printf '%s\n' "$f"
  done
}

shell_files() {
  local f
  own_files | while IFS= read -r f; do
    case $f in
      *.sh | *.bash) printf '%s\n' "$f" ;;
      *.*) ;;
      *) head -n 1 "$f" 2>/dev/null | grep -q -E '^#!.*\b(ba)?sh\b' && printf '%s\n' "$f" ;;
    esac
  done
}

yaml_files() {
  own_files '*.yml' '*.yaml'
}

has_files() { [[ -n $(list_files "$@" | head -n 1) ]]; }

# ---------------------------------------------------------------- gates
gate_ruff() { run_gate ruff ruff -- "$(tool ruff)" check --no-cache .; }
gate_ruff-format() { run_gate ruff-format ruff -- "$(tool ruff)" format --check --no-cache .; }
gate_codespell() { run_gate codespell codespell -- "$(tool codespell)"; }
gate_vulture() { run_gate vulture vulture -- "$(tool vulture)"; }
gate_deptry() { run_gate deptry deptry -- "$(tool deptry)" .; }
# B = cyclomatic complexity <= 10 per block, matching ruff's C901 default.
gate_xenon() {
  run_gate xenon xenon -- "$(tool xenon)" --max-absolute B --max-modules A --max-average A src
}
gate_reuse() { run_gate reuse reuse -- "$(tool reuse)" lint; }

gate_yamllint() {
  local -a files
  mapfile -t files < <(yaml_files)
  ((${#files[@]})) || {
    skip yamllint "no YAML files"
    return
  }
  run_gate yamllint yamllint -- "$(tool yamllint)" --strict "${files[@]}"
}

own_files() { list_files "$@" | grep -v -E "$RIG_MANAGED_RE"; }

gate_actionlint() {
  local -a files
  mapfile -t files < <(own_files '.github/workflows/*.yml' '.github/workflows/*.yaml')
  ((${#files[@]})) || {
    skip actionlint "no workflows"
    return
  }
  run_gate actionlint actionlint -- "$(tool actionlint)" "${files[@]}"
}

gate_zizmor() {
  local -a files
  # Git pathspec `*` crosses `/`; `**/` would require a subdirectory and miss dependabot.yml.
  mapfile -t files < <(own_files '.github/*.yml' '.github/*.yaml')
  ((${#files[@]})) || {
    skip zizmor "no .github"
    return
  }
  run_gate zizmor zizmor -- "$(tool zizmor)" --no-progress "${files[@]}"
}

gate_shellcheck() {
  local -a files
  mapfile -t files < <(shell_files)
  ((${#files[@]})) || {
    skip shellcheck "no shell scripts"
    return
  }
  run_gate shellcheck shellcheck -- "$(tool shellcheck)" --severity=style --external-sources "${files[@]}"
}

gate_shfmt() {
  local -a files
  mapfile -t files < <(shell_files)
  ((${#files[@]})) || {
    skip shfmt "no shell scripts"
    return
  }
  run_gate shfmt shfmt -- "$(tool shfmt)" --diff --indent 2 --case-indent "${files[@]}"
}

gate_mypy() { run_gate mypy mypy -- "$(tool mypy)" --no-incremental; }
gate_pyright() { run_gate pyright pyright -- "$(tool pyright)" --pythonpath "$PYTHON"; }

gate_bandit() {
  run_gate bandit bandit -- "$(tool bandit)" --configfile pyproject.toml --recursive --quiet src
}

# Registry packs need the network; the project rules in .semgrep/ always run, so an offline
# machine still enforces the repository-specific bans.
semgrep_args() {
  local -a args=(scan --metrics=off --error --quiet --config .semgrep/)
  if [[ ${CHECK_OFFLINE:-0} != 1 ]]; then
    args+=(--config p/python --config p/security-audit --config p/secrets)
  fi
  printf '%s\n' "${args[@]}"
}

gate_semgrep() {
  local -a args
  mapfile -t args < <(semgrep_args)
  run_gate semgrep semgrep -- "$(tool semgrep)" "${args[@]}" src tests scripts
}

# Audits the declared dependency closure, not the venv: the venv sees Ubuntu's system
# site-packages, whose Debian version strings make pip-audit report noise.
pip_audit_resolved() {
  local req
  req=$(mktemp) || return 2
  uv pip compile --quiet --no-header --python "$PYTHON" --group pyproject.toml:dev pyproject.toml -o "$req" &&
    "$(tool pip-audit)" --strict --progress-spinner off --disable-pip --no-deps -r "$req"
  local rc=$?
  rm -f "$req"
  return "$rc"
}
gate_pip-audit() { run_gate pip-audit pip-audit,uv -- pip_audit_resolved; }

gate_gitleaks() {
  if git rev-parse --verify -q HEAD >/dev/null; then
    run_gate gitleaks gitleaks -- "$(tool gitleaks)" git --no-banner --redact .
  else
    run_gate gitleaks gitleaks -- "$(tool gitleaks)" dir --no-banner --redact src tests scripts data
  fi
}

gate_dbus-xml() {
  local -a files
  mapfile -t files < <(list_files 'data/dbus/*.xml')
  ((${#files[@]})) || {
    skip dbus-xml "no D-Bus interface XML"
    return
  }
  run_gate dbus-xml gdbus-codegen -- validate_dbus_xml "${files[@]}"
}
validate_dbus_xml() {
  local out rc
  out=$(mktemp -d) || return 2
  gdbus-codegen --output-directory "$out" --generate-c-code check "$@"
  rc=$?
  rm -rf "$out"
  return "$rc"
}

