gate_gschema() {
  local -a dirs
  mapfile -t dirs < <(list_files 'data/*.gschema.xml' | xargs -r -n1 dirname | sort -u)
  ((${#dirs[@]})) || {
    skip gschema "no GSettings schemas"
    return
  }
  run_gate gschema glib-compile-schemas -- compile_schemas "${dirs[@]}"
}
compile_schemas() {
  local d
  for d in "$@"; do
    glib-compile-schemas --strict --dry-run "$d" || return 1
  done
}

# Extension gates call the binaries Task F pins in extension/package.json devDependencies.
ext_bin() { printf '%s\n' "$ROOT/extension/node_modules/.bin/$1"; }
ext_ready() {
  [[ -f extension/package.json ]] || return 1
  [[ -d extension/node_modules ]] || (cd extension && bun install --frozen-lockfile) >&2
}
ext_gate() { # name tool args...
  local name=$1 bin=$2
  shift 2
  if [[ ! -f extension/package.json ]]; then
    skip "$name" "no extension/"
    return
  fi
  if ! ext_ready; then
    record "$name" FAIL 0 "bun install failed"
    return
  fi
  if [[ ! -x $(ext_bin "$bin") ]]; then
    record "$name" FAIL 0 "$bin not in extension devDependencies"
    return
  fi
  run_gate "$name" bun -- in_extension "$(ext_bin "$bin")" "$@"
}
in_extension() { (cd extension && "$@"); }
gate_eslint() { ext_gate eslint eslint --max-warnings 0 .; }
gate_tsc() { ext_gate tsc tsc --noEmit -p .; }
gate_prettier() { ext_gate prettier prettier --check .; }
gate_web-ext() {
  # Rebuild every run: a stale dist/ would let web-ext pass on outdated output.
  if [[ -f extension/package.json ]]; then
    if ! ext_ready; then
      record web-ext FAIL 0 "bun install failed"
      return
    fi
    in_extension bun run build >&2 || {
      record web-ext FAIL 0 "bun run build failed"
      return
    }
  fi
  ext_gate web-ext web-ext lint --source-dir dist/firefox --warnings-as-errors
}
gate_bun-audit() {
  if [[ ! -f extension/package.json ]]; then
    skip bun-audit "no extension/"
    return
  fi
  run_gate bun-audit bun -- in_extension bun audit
}
gate_semgrep-ts() {
  if [[ ! -f extension/package.json ]]; then
    skip semgrep-ts "no extension/"
    return
  fi
  run_gate semgrep-ts semgrep -- "$(tool semgrep)" scan --metrics=off --error --quiet \
    --config p/typescript --config p/secrets --exclude node_modules --exclude dist extension
}

# Unit and integration runs append to one coverage data file so the coverage gate can report
# on both without running the suites a second time.
pytest_layer() { # name marker-expression workers [extra pytest args...]
  run_gate "$1" pytest -- nice -n 10 "$PYTHON" -m pytest "${PYTEST_COMMON[@]}" \
    -n "$3" -m "$2" "${@:4}"
}
COV_ARGS=(--cov=passwords_app --cov-append --cov-report=)
gate_unit() { pytest_layer unit "$PYTEST_FAST_EXCLUDE" "$PYTEST_WORKERS" "${COV_ARGS[@]}"; }
gate_integration() {
  pytest_layer integration "integration and not live" "$PYTEST_WORKERS" "${COV_ARGS[@]}"
}
gate_coverage() {
  [[ -n ${RAN[unit]:-} ]] || gate_unit
  [[ -n ${RAN[integration]:-} ]] || gate_integration
  run_gate coverage coverage -- "$(tool coverage)" report --fail-under="$COVERAGE_MIN" \
    --include="$COVERAGE_INCLUDE"
}
# Headless gnome-shell sessions are serialized by the harness; one worker avoids queueing.
gate_gui() { pytest_layer gui "gui and not live" 0; }
gate_e2e() { pytest_layer e2e "e2e and not live" 0; }
gate_browser() { pytest_layer browser "browser and not live" 0; }
gate_bench() { pytest_layer bench "benchmark and not live" 0 --benchmark-only; }

# ---------------------------------------------------------------- driver
group_members() { # group -> its gate names
  local -a gates
  read -r -a gates <<<"${GROUP_GATES[$1]}"
  printf '%s\n' "${gates[@]}"
}

all_gates() {
  local g
  for g in "${GATE_GROUPS[@]}"; do
    group_members "$g"
  done
}

expand() { # args -> gate names
  local a
  for a in "$@"; do
    if [[ $a == all ]]; then
      all_gates
    elif [[ -n ${GROUP_GATES[$a]:-} ]]; then
      group_members "$a"
    # No `grep -q`: its early exit SIGPIPEs the producer and pipefail turns a match into failure.
    elif all_gates | grep -x -- "$a" >/dev/null; then
      printf '%s\n' "$a"
    else
      printf 'unknown group or gate: %s\n' "$a" >&2
      return 2
    fi
  done
}

print_table() {
  local i fails=0
  printf '\n%-14s %-5s %6s  %s\n' GATE RESULT SECS DETAIL
  printf '%s\n' "------------------------------------------------------------------------------------------"
  for i in "${!R_NAME[@]}"; do
    printf '%-14s %-5s %6s  %s\n' "${R_NAME[$i]}" "${R_STATUS[$i]}" "${R_SECS[$i]}" "${R_DETAIL[$i]}"
    [[ ${R_STATUS[$i]} == FAIL ]] && fails=$((fails + 1))
  done
  printf '\n%d gate(s): %d failed. Logs: %s/\n' "${#R_NAME[@]}" "$fails" "${LOG_DIR#"$ROOT"/}"
  ((fails == 0))
}

main() {
  if [[ ${1:-} == -h || ${1:-} == --help ]]; then
    usage
    return 0
  fi
  if [[ ${1:-} == --list ]]; then
    all_gates
    return 0
  fi
  local listing
  listing=$(expand "${@:-all}") || {
    usage >&2
    return 2
  }
  local -a gates
  mapfile -t gates <<<"$listing"
  mkdir -p "$LOG_DIR"
  # Coverage data is appended per invocation; stale data from an older run would inflate it.
  if printf '%s\n' "${gates[@]}" | grep -xE 'unit|integration|coverage' >/dev/null; then
    rm -f .coverage .coverage.*
  fi
  local g
  for g in "${gates[@]}"; do
    [[ -n ${RAN[$g]:-} ]] && continue
    "gate_$g"
  done
  print_table
}

main "$@"
